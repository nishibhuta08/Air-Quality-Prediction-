# Re-scale the entire X for sequence modeling, as the original split was shuffled
# and X_scaled was not globally defined.
# Using a fresh scaler for this specific model block to avoid interference with previous scaling.
scaler_lstm = MinMaxScaler()
X_scaled = scaler_lstm.fit_transform(X) # X is the one-hot encoded DataFrame

# Create sequences for LSTM
sequence_length = 10
X_seq, y_seq = [], []

# For sequence models, we should typically preserve temporal order.
# The original X and y are already ordered by date due to previous processing.
# However, the earlier train_test_split shuffled the data for non-sequential models.
# For LSTM, we will split the *sequences* chronologically.

for i in range(sequence_length, len(X_scaled)):
    X_seq.append(X_scaled[i-sequence_length:i])
    y_seq.append(y.iloc[i])

X_seq = np.array(X_seq)
y_seq = np.array(y_seq)

# Split sequences chronologically (e.g., 80% for training, 20% for testing)
split_idx = int(0.8 * len(X_seq))
X_train_lstm, X_test_lstm = X_seq[:split_idx], X_seq[split_idx:]
y_train_lstm, y_test_lstm = y_seq[:split_idx], y_seq[split_idx:]

print(f"Sequence shape: {X_seq.shape}")
print(f"X_train_lstm shape: {X_train_lstm.shape}")
print(f"X_test_lstm shape: {X_test_lstm.shape}")

# Build LSTM model
lstm_model = Sequential([
    LSTM(64, return_sequences=True, input_shape=(X_train_lstm.shape[1], X_train_lstm.shape[2])),
    Dropout(0.2),
    LSTM(32),
    Dropout(0.2),
    Dense(1)
])
lstm_model.compile(optimizer='adam', loss='mse')

start_time = time.time()
lstm_model.fit(X_train_lstm, y_train_lstm, epochs=15, batch_size=32, validation_split=0.2, verbose=0)
lstm_latency = time.time() - start_time

lstm_pred = lstm_model.predict(X_test_lstm, verbose=0).flatten()

lstm_mae = mean_absolute_error(y_test_lstm, lstm_pred)
lstm_rmse = np.sqrt(mean_squared_error(y_test_lstm, lstm_pred))
