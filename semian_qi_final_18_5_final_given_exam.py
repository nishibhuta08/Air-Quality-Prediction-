def get_aqi_from_openweather(api_key, latitude, longitude):
    """
    Fetch real-time AQI data from OpenWeatherMap API

    Sign up free at: https://home.openweathermap.org/users/sign_up
    """

    url = f"http://api.openweathermap.org/data/2.5/air_pollution?lat={latitude}&lon={longitude}&appid={api_key}"

    response = requests.get(url)
    data = response.json()

    if response.status_code == 200:
        components = data['list'][0]['components']

        return {
            'PM2.5': components.get('pm2_5', 0),
            'PM10': components.get('pm10', 0),
            'NO2': components.get('no2', 0),
            'NO': components.get('no', 0),
            'NH3': components.get('nh3', 0),
            'CO': components.get('co', 0),
            'SO2': components.get('so2', 0),
            'O3': components.get('o3', 0),
            'AQI': data['list'][0]['main']['aqi'],  # 1=Good, 2=Fair, 3=Moderate, 4=Poor, 5=Very Poor
            'timestamp': datetime.now()
        }
    else:
        print(f"API Error: {response.status_code}")
        return None

